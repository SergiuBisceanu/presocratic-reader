"""Build the approved static assets for their configured Pages address."""
import argparse
import json
import os
import re
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit, urljoin, unquote
import xml.etree.ElementTree as ET

TEXT_SUFFIXES = {'.html', '.js', '.css', '.json', '.xml', '.txt', '.csv', '.svg'}

ROOT_FILES = {'index.html', 'app.js', 'lsj.js', 'research.js', 'research-core.js', 'research.css', 'discovery.css', 'meaning.js', 'meaning-core.js', 'meaning-worker.js', 'transmission.js', 'style.css', 'favicon.svg', 'robots.txt',
              'sitemap.xml', 'licences.txt'}

PUBLIC_DIRECTORIES = {'read', 'data', 'art', 'fonts', 'attribution', 'catalogue', 'coverage', 'concordance', 'find', 'sources', 'models', 'vendor'}

LOCAL_PREFIXES = ('/read/', '/data/', '/art/', '/fonts/', '/attribution/', '/catalogue/', '/coverage/', '/concordance/', '/find/', '/sources/', '/models/', '/vendor/')

SITE_IDENTITY = re.compile(r'appg(?:prj|ver|dep)_[a-zA-Z0-9_~]+|git\.chatgpt-team\.site')

def settings(origin, base_path, cname=None):
    parsed = urlsplit(origin)
    if (parsed.scheme != 'https' or not parsed.hostname or parsed.port or
            parsed.username or parsed.password or parsed.query or parsed.fragment or
            parsed.path not in ('', '/') or
            not re.fullmatch(r'[a-zA-Z0-9.-]+', parsed.hostname)):
        raise ValueError('Use an HTTPS origin without a path, port, query or credentials.')
    origin = 'https://' + parsed.hostname.lower()
    if not re.fullmatch(r'/(?:[a-zA-Z0-9_-]+/)*', base_path):
        raise ValueError('The base path must be / or slash-delimited simple path segments ending in /.')
    if cname:
        if cname.lower() != parsed.hostname.lower() or base_path != '/':
            raise ValueError('CNAME must match the origin hostname and requires base path /.')
        if parsed.hostname.endswith('.github.io'):
            raise ValueError('Do not create CNAME for GitHub’s supplied github.io address.')
    return origin, base_path, cname.lower() if cname else None

class HomeOrigin(HTMLParser):
    origin = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'link' and attrs.get('rel') == 'canonical':
            parsed = urlsplit(attrs['href'])
            if parsed.path != '/':
                raise ValueError('Expected the original build to be hosted at its origin root.')
            self.origin = parsed.scheme + '://' + parsed.netloc

def local_url(value, base_path):
    if value == '/' or value.startswith(LOCAL_PREFIXES) or value in (
            '/app.js', '/lsj.js', '/research.js', '/research-core.js', '/research.css', '/discovery.css', '/meaning.js', '/meaning-core.js', '/meaning-worker.js', '/transmission.js', '/style.css', '/favicon.svg', '/licences.txt', '/sitemap.xml', '/robots.txt'):
        return base_path + value[1:]
    return value

def transform_html(text, old_origin, new_origin, base_path):
    # Attribute-only rewriting preserves the source text and translation markup.
    # Replace the exact own origin once, before processing relative attributes.
    text = text.replace(old_origin + '/', new_origin + base_path)
    attribute = re.compile(r'(\b(?:href|src|action|poster)\s*=\s*)([\'\"])(.*?)\2', re.I | re.S)
    def replace(match):
        value = local_url(match[3], base_path)
        return match[1] + match[2] + value + match[2]
    text = attribute.sub(replace, text)
    return text

def transform_js(text, base_path):
    if base_path == '/':
        return text
    pathname = "location.pathname.replace(/^\\/|\\/$/g,'')"
    if text.count(pathname) != 1:
        raise ValueError('Reader route parser changed; review the GitHub base-path adapter.')
    root_redirect = ":'/';location.replace(target);"
    if text.count(root_redirect) != 1:
        raise ValueError('Legacy home redirect changed; review the GitHub base-path adapter.')
    text = text.replace(pathname, "readerPathname().replace(/^\\/|\\/$/g,'')")
    text = text.replace(root_redirect, ':' + json.dumps(base_path) + ';location.replace(target);')
    # Only string/template URL prefixes are changed. Slash keyboard shortcuts,
    # regular expressions, separators and legacy #/ routes are left untouched.
    text = re.sub(r'([\'\"`])/(?=(?:read|data|art|fonts|attribution|catalogue|coverage|concordance|find|sources)/)',
                  lambda m: m[1] + base_path, text)
    adapter = (
        '// GitHub Pages project path; generated by export-github.py.\n'
        'const READER_BASE_PATH = ' + json.dumps(base_path) + ';\n'
        'function readerPathname(){\n'
        ' const path=location.pathname;\n'
        ' if(path===READER_BASE_PATH.slice(0,-1))return "/";\n'
        ' return path.startsWith(READER_BASE_PATH)?"/"+path.slice(READER_BASE_PATH.length):path;\n'
        '}\n'
    )
    return adapter + text

def transform_json(value, old_origin, new_origin, base_path):
    if isinstance(value, list):
        return [transform_json(v, old_origin, new_origin, base_path) for v in value]
    if isinstance(value, dict):
        return {k: transform_json(v, old_origin, new_origin, base_path) for k, v in value.items()}
    if isinstance(value, str):
        if value.startswith(old_origin + '/'):
            return new_origin + base_path + value[len(old_origin) + 1:]
        if value.startswith(LOCAL_PREFIXES):
            return local_url(value, base_path)
    return value

def transform_file(relative, data, old_origin, origin, base_path):
    # Pinned model/runtime assets use relative URLs and integrity manifests.
    # Preserve their exact bytes, including upstream JSON configuration.
    if relative.parts[0] in {'models', 'vendor'}:
        return data
    if relative.suffix not in TEXT_SUFFIXES:
        return data
    text = data.decode('utf-8')
    if relative.suffix == '.html':
        text = transform_html(text, old_origin, origin, base_path)
    elif str(relative) == 'app.js':
        text = transform_js(text, base_path)
    elif relative.suffix == '.css':
        text = re.sub(r'(url\(\s*[\'\"]?)(/[^\s\)\'\"]+)',
                      lambda m: m[1] + local_url(m[2], base_path), text)
    elif relative.suffix == '.json':
        text = json.dumps(transform_json(json.loads(text), old_origin, origin, base_path),
                          ensure_ascii=False, separators=(',', ':'))
    else:
        text = text.replace(old_origin + '/', origin + base_path)
    if str(relative) == 'robots.txt':
        text = f'User-agent: *\nAllow: {base_path}\nSitemap: {origin}{base_path}sitemap.xml\n'
    if old_origin != origin and old_origin in text:
        raise ValueError('Old hosting origin remains in ' + str(relative))
    if SITE_IDENTITY.search(text):
        raise ValueError('Hosting repository identity appears in delivered asset ' + str(relative))
    return text.encode('utf-8')

TEXT_SUFFIXES.add('.bib')


class PageLinks(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links, self.ids, self.canonical = [], set(), None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if attrs.get('id'):
            self.ids.add(attrs['id'])
        for field in ('href', 'src', 'poster', 'action'):
            if attrs.get(field):
                self.links.append(attrs[field])
        if tag == 'link' and attrs.get('rel') == 'canonical':
            self.canonical = attrs.get('href')


def validate_output(output, origin, base_path):
    pages = {}
    for path in output.rglob('*.html'):
        page = PageLinks()
        page.feed(path.read_text())
        pages[path.relative_to(output)] = page
    checked = 0
    for relative, page in pages.items():
        address = origin + base_path + str(relative).removesuffix('index.html')
        if page.canonical != address:
            raise ValueError('Incorrect canonical address: ' + str(relative))
        for value in page.links:
            url = urlsplit(urljoin(address, value))
            if url.scheme not in ('http', 'https') or url.netloc != urlsplit(origin).netloc:
                continue
            if not url.path.startswith(base_path):
                raise ValueError('Local link escapes the project path: ' + value)
            destination = output / unquote(url.path[len(base_path):])
            if destination.is_dir():
                destination /= 'index.html'
            if not destination.is_file() or output not in destination.resolve().parents:
                raise ValueError('Missing or unsafe local link: ' + value)
            if url.fragment and destination.suffix == '.html':
                if unquote(url.fragment) not in pages[destination.relative_to(output)].ids:
                    raise ValueError('Missing fragment anchor: ' + value)
            checked += 1
    locations = [node.text for node in ET.parse(output / 'sitemap.xml').iter('{http://www.sitemaps.org/schemas/sitemap/0.9}loc')]
    expected = {origin + base_path + str(page).removesuffix('index.html') for page in pages}
    if not (output / 'app.js').is_file():
        expected.update(origin + base_path + str(path.relative_to(output)) for path in output.rglob('*.pdf'))
    if set(locations) != expected or len(locations) != len(expected):
        raise ValueError('The sitemap does not match the published pages.')
    for stylesheet in output.rglob('*.css'):
        address = origin + base_path + str(stylesheet.relative_to(output))
        for value in re.findall(r'url\(\s*[\'\"]?([^\s\)\'\"]+)', stylesheet.read_text()):
            url = urlsplit(urljoin(address, value))
            if url.scheme not in ('http', 'https') or url.netloc != urlsplit(origin).netloc:
                continue
            if not url.path.startswith(base_path):
                raise ValueError('Stylesheet asset escapes the project path: ' + value)
            target = output / unquote(url.path[len(base_path):])
            if not target.is_file() or output not in target.resolve().parents:
                raise ValueError('Missing stylesheet asset: ' + value)
            checked += 1
    for source in output.rglob('*'):
        if source.is_file() and source.suffix in TEXT_SUFFIXES:
            if 'publication.invalid' in source.read_text():
                raise ValueError('Unconfigured publication address: ' + str(source))
    print(json.dumps(dict(pages=len(pages), internalLinks=checked, url=origin + base_path)))


def build(base_url, destination):
    if not base_url or base_url.strip() != base_url:
        raise ValueError('PAGES_BASE_URL must be supplied by the configured GitHub Pages environment.')
    url = urlsplit(base_url)
    if url.query or url.fragment or not url.hostname or url.hostname.endswith('.invalid'):
        raise ValueError('Use the actual configured HTTPS Pages address.')
    origin, base_path, _ = settings(url.scheme + '://' + url.netloc, (url.path.rstrip('/') + '/') or '/')
    root = Path(__file__).resolve().parents[1]
    source = root / 'site'
    destination = Path(destination).resolve()
    if destination == root or destination == source or source in destination.parents or destination in source.parents:
        raise ValueError('Build output must be separate from the source site.')
    if destination.exists() and (not destination.is_dir() or any(destination.iterdir())):
        raise ValueError('Build output must be new or empty; existing files are never overwritten.')
    parser = HomeOrigin()
    parser.feed((source / 'index.html').read_text())
    if parser.origin != 'https://publication.invalid':
        raise ValueError('Expected an unconfigured root-layout publication source.')
    files = []
    is_reader = (source / 'app.js').is_file()
    for path in sorted(source.rglob('*')):
        if path.is_symlink():
            raise ValueError('Symlinks are not publication assets.')
        if not path.is_file():
            continue
        relative = path.relative_to(source)
        if str(relative) == '.nojekyll':
            continue
        if any(part.startswith('.') for part in relative.parts):
            raise ValueError('Unexpected hidden publication asset: ' + str(relative))
        allowed = ((len(relative.parts) == 1 and (str(relative) in ROOT_FILES or (not is_reader and relative.suffix in {'.pdf', '.bib'}))) or
                   (len(relative.parts) > 1 and relative.parts[0] in PUBLIC_DIRECTORIES))
        if not allowed:
            raise ValueError('Unexpected publication asset: ' + str(relative))
        data = transform_file(relative, path.read_bytes(), parser.origin, origin, base_path)
        files.append((relative, data))
    destination.mkdir(parents=True, exist_ok=True)
    for relative, data in files:
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    (destination / '.nojekyll').write_text('')
    validate_output(destination, origin, base_path)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Build the static publication for the configured GitHub Pages address.')
    parser.add_argument('--base-url', default=os.environ.get('PAGES_BASE_URL'))
    parser.add_argument('--output', default='_site')
    args = parser.parse_args()
    try:
        build(args.base_url, args.output)
    except (ValueError, OSError, ET.ParseError) as error:
        parser.exit(1, str(error) + '\n')
